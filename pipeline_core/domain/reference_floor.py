# Cargo labels its doc-test section `Doc-tests <crate>`; every other section is
# labelled from the `Running <desc> (<path>)` stderr line.
_DOC_LABEL_PREFIX = "Doc-tests "
_LINE_SUFFIX_OPEN = " (line "
_TEST_MOD_NAMES = frozenset({"test", "tests"})
_GEN_TESTS_PREFIX = "gen_tests_"


def _is_test_module_segment(segment: str) -> bool:
    """Whether one `::` segment of a test path names the module a crate keeps
    its inline unit tests in — either the crate's own (`mod tests`) or the one
    this pipeline relocates them into (`gen_tests_<N>`)."""
    if segment in _TEST_MOD_NAMES:
        return True
    tail = segment[len(_GEN_TESTS_PREFIX):]
    return segment.startswith(_GEN_TESTS_PREFIX) and tail.isdigit()


def is_doc_pair(pair: tuple[str, str]) -> bool:
    """Whether this `(binary_label, test_name)` came from the doc-test target."""
    return pair[0].startswith(_DOC_LABEL_PREFIX)


# rustdoc appends the mode of a doc test that is only compiled: `no_run`
# reads `src/lib.rs - a (line 8) - compile`, `compile_fail` reads
# `… (line 11) - compile fail` (rustdoc on rustc 1.97, 2026-11-02). A parser
# that wanted the name to end in `)` read neither as a doc test, so their line
# was never stripped and they could never match across two trees.
_DOC_MODE_SUFFIXES = (" - compile fail", " - compile")


def _doc_name(test_name: str) -> tuple[str, int] | None:
    """`(item head, line)` of a doc test's libtest name, or None when the
    name is not a doc test's."""
    name = test_name.strip()
    for suffix in _DOC_MODE_SUFFIXES:
        if name.endswith(suffix):
            name = name[:-len(suffix)].rstrip()
            break
    if not name.endswith(")") or _LINE_SUFFIX_OPEN not in name:
        return None
    head, _, tail = name.rpartition(_LINE_SUFFIX_OPEN)
    digits = tail[:-1].strip()
    return (head.rstrip(), int(digits)) if digits.isdigit() else None


def doc_test_line(test_name: str) -> int | None:
    """The source line a doc test's ``` block opens on, or None if the name
    carries no such suffix (i.e. it is not a doc test)."""
    parsed = _doc_name(test_name)
    return parsed[1] if parsed else None


def doc_test_head(test_name: str) -> str | None:
    """A doc test's name without its line and mode (`src/lib.rs - Context`),
    or None if it is not a doc test."""
    parsed = _doc_name(test_name)
    return parsed[0] if parsed else None


def doc_test_keys(names: Iterable[str]) -> dict[str, str]:
    """Each doc test name of ONE binary → its stable key: the head plus the
    example's ordinal among that head's doc tests in source order, counted
    over every verdict. An ordinal counted per verdict made a passing and an
    ignored example of one item both `#0`, so one key named two tests.
    Names that are not doc tests are left out."""
    out: dict[str, str] = {}
    ordinal: dict[str, int] = {}
    for n in sorted(names, key=lambda x: (doc_test_line(x) or 0, x)):
        head = doc_test_head(n)
        if head is None:
            continue
        k = ordinal.get(head, 0)
        ordinal[head] = k + 1
        out[n] = f"{head}#{k}"
    return out


def normalize_pair(label: str, test_name: str) -> tuple[str, str]:
    """The comparison key for one test verdict, stable across trees.

    Everything but a doc test is already stable: the pair is
    (`Running` description, `#[test]` fn path). A doc test's name ends in the
    source line its ``` block opens on, which moves whenever the reconstructed
    file's length differs from upstream's — so comparing raw names reports every
    doc test as missing, forever, on every run, and makes this floor strictly
    harder to satisfy than the absolute it replaces. Measured 2026-08-06:
    `context::Option<T>` is line 70 upstream and 55 in the reconstruction,
    `Error::chain` 426 vs 404, `Error::context` 311 vs 299.

    Stripping the line alone is LOSSY, and `pairs_of` is where that is repaired:
    one documented item may carry several examples, so `src/lib.rs - Context`
    names three distinct doc tests in `anyhow` (upstream lines 479, 543, 583)
    and `src/lib.rs - ` names six. Collapsing them took the reference's 26 doc
    tests to 16 and its 98 passing tests to 88 — a floor that then treats one
    surviving `Context` example as satisfying all three.

    The other rename is this pipeline's own. Inline `#[cfg(test)] mod`s are
    relocated pre-strip into `<stem>.gen_tests_N.rs` siblings, so a unit test
    upstream runs as `fmt::tests::no_digits` and the SAME test runs here as
    `fmt::gen_tests_1::no_digits`. Measured 2026-08-06 against pristine
    `1dbe1862`, that was the ENTIRE difference the floor reported on a tree that
    otherwise meets it: three tests — `fmt::tests::no_digits`, `one_digit`,
    `two_digits` — read as missing in both clusters while `fmt.gen_tests_1.rs`
    was passing 3/3 the whole time. Dropping the test-module segment makes the
    two names the same fact. Safe in the direction that matters: a crate keeps
    one such module per file, so nothing collapses on the REFERENCE side, and
    extra collapsing on ours can only let a requirement be satisfied by a test
    that genuinely passes.
    """
    name = test_name.strip()
    head = doc_test_head(name)
    if head is not None:
        name = head
    elif "::" in name:
        kept = [s for s in name.split("::") if not _is_test_module_segment(s)]
        name = "::".join(kept) or name
    return (label.strip(), name)


def pairs_of(binaries: Iterable[object]) -> tuple[
        frozenset[tuple[str, str]], frozenset[tuple[str, str]],
        frozenset[tuple[str, str]], frozenset[str]]:
    """`(passed, failed, ignored, incomplete_labels)` as NORMALIZED pairs from
    `test_results.parse_binary_results` output.

    Several doc tests can normalize to one name — they are distinct examples on
    the same documented item — so each gets an ordinal within its binary,
    assigned in SOURCE order (by the line number the name carried). Source order
    is what corresponds across two trees of the same crate: the k-th example of
    `src/lib.rs - Context` upstream is the k-th here, whatever line either sits
    on, and cargo's own emission order is a parallel-execution artefact that
    corresponds to nothing. Ordinals are applied to every doc pair, never only
    to the ambiguous ones, so a tree holding 1 of 3 examples reports 2 missing
    rather than 0.

    Typed on `object` for the same reason `measurement.qualified_verdicts` is:
    this module must not import `domain.test_results`, and the only shape needed
    is `label` / `passed` / `failed` / `ignored` / `completed`.
    """
    passed: set[tuple[str, str]] = set()
    failed: set[tuple[str, str]] = set()
    ignored: set[tuple[str, str]] = set()
    incomplete: set[str] = set()
    sinks = {"passed": passed, "failed": failed, "ignored": ignored}
    for b in binaries:
        for attr, _raw, pair in binary_pairs(b):
            sinks[attr].add(pair)
        if not getattr(b, "completed", True):
            incomplete.add(str(getattr(b, "label", "?")))
    return frozenset(passed), frozenset(failed), frozenset(ignored), frozenset(incomplete)


def binary_pairs(b: object) -> tuple[tuple[str, str, tuple[str, str]], ...]:
    """`(verdict, libtest name, normalized pair)` for every test of one
    binary: the one place a raw name becomes its comparison key
    (:func:`pairs_of` is this, summed). The raw name is what runs the test
    again; the pair is what the reference keys it by."""
    label = str(getattr(b, "label", "?"))
    by_attr = {attr: [str(n) for n in getattr(b, attr, ())]
               for attr in ("passed", "failed", "ignored")}
    keys = doc_test_keys(n for names in by_attr.values() for n in names)
    out: list[tuple[str, str, tuple[str, str]]] = []
    for attr, raw in by_attr.items():
        for name in sorted(raw, key=lambda n: (doc_test_line(n) or 0, n)):
            key = keys.get(name)
            out.append((attr, name, (label.strip(), key) if key is not None
                        else normalize_pair(label, name)))
    return tuple(out)


@dataclass(frozen=True, slots=True)
class ClusterReference:
    """What the pristine tree did in ONE baked cluster — an oracle vector and
    nothing else.

    No bodies, no source text, no file contents. This object is allowed to reach
    a verdict; it must never reach a prompt. The moment a reference measurement
    is rendered into a model call the pipeline stops reconstructing and starts
    copying, and every score it has ever recorded becomes meaningless.

    `failures` is how the original failed each test it failed, read twice in
    two processes (`same_failure`), and it is the ONLY record of which tests
    failed: `failed` is its key set. A failed test cannot be recorded without
    an entry, so a store row or a caller that names a failure and skips the
    alone read does not exist; a failure the measurement could not read is
    an explicit `ReferenceFailure()` and is reported as excused by name. The
    readings are the original's OUTPUT, which can quote the original's
    source, so they are held for comparison only: the judge compares them
    and prints this tree's side of a difference, never theirs.

    There is deliberately no "neutral" set. What the original's failures
    excuse is a decision (:func:`judge_against_reference`), and a reader that
    took the failed names as excused would rebuild the name-only excuse this
    field exists to retire.
    """

    cluster: str
    passed: frozenset[tuple[str, str]] = frozenset()
    failures: Mapping[tuple[str, str], ReferenceFailure] = field(default_factory=dict)
    ignored: frozenset[tuple[str, str]] = frozenset()
    incomplete: frozenset[str] = frozenset()
    announced: int = 0
    reported: int = 0
    rc: int = 0
    # Each doc test's place, as rustdoc named it: normalized pair → (file,
    # line). Lines of the original; held for the join below, never shown.
    doc_lines: Mapping[tuple[str, str], tuple[str, int]] = field(default_factory=dict)
    # What stands for each doc test in the oracle (`domain.doc_stand_in`):
    # its re-hosted example's pair, or why there is none.
    doc_covers: Mapping[tuple[str, str], DocCover] = field(default_factory=dict)

    @property
    def failed(self) -> frozenset[tuple[str, str]]:
        """The tests the original failed: the keys of `failures`."""
        return frozenset(self.failures)

    @property
    def unhealthy_reason(self) -> str:
        """Why this reference may not be used as a bar, or "" when it may.

        A silently-broken reference LOWERS the bar invisibly, which is the one
        way this whole mechanism can do harm: every test it failed to run
        becomes neutral, and a reconstruction failing those tests reads as done.
        So the checks are on the reference's own internal consistency — never on
        whether it looks "good" — and any of them failing sends the caller back
        to the absolute criterion with a log line saying so.
        """
        if self.incomplete:
            return (f"{len(self.incomplete)} binary/binaries crashed without a "
                    f"`test result:` trailer ({', '.join(sorted(self.incomplete))})")
        if self.announced != self.reported:
            return (f"cargo announced {self.announced} test(s) and reported "
                    f"{self.reported}")
        if not self.passed:
            return "no passing test observed at all"
        return ""

    @property
    def healthy(self) -> bool:
        return not self.unhealthy_reason


@dataclass(frozen=True, slots=True)
class FloorVerdict:
    """Whether one cluster met the reference, and exactly what it missed."""

    cluster: str
    unmet: frozenset[tuple[str, str]] = frozenset()
    unexcused_failures: frozenset[tuple[str, str]] = frozenset()
    advisory_unmet: frozenset[tuple[str, str]] = frozenset()
    exceeded: int = 0
    # Failing here, failed by the original too, and NOT the same failure:
    # the original's reading was stable and this tree's differs or could not
    # be read. Gates like an unexcused failure. `divergence` says where.
    diverged: frozenset[tuple[str, str]] = frozenset()
    divergence: Mapping[tuple[str, str], str] = field(default_factory=dict)
    # Failing here and excused: the same failure the original's, or a test
    # the original skipped.
    excused: frozenset[tuple[str, str]] = frozenset()
    # Of `excused`, those excused by name only, because the original's own
    # failure gave no stable reading to compare (two runs differed, or it
    # could not be read). Logged, never silent.
    excused_by_name: frozenset[tuple[str, str]] = frozenset()
    # Of the reference's doc tests absent here, those whose re-hosted example
    # passes here: met through their stand-in, not reported.
    doc_stand_ins: frozenset[tuple[str, str]] = frozenset()
    # Why each `advisory_unmet` pair has no stand-in that passed.
    advisory_gaps: Mapping[tuple[str, str], str] = field(default_factory=dict)

    @property
    def met(self) -> bool:
        return not self.unmet and not self.unexcused_failures and not self.diverged

    @property
    def reason(self) -> str:
        if self.met:
            note = (f"met the reference floor"
                    f"{f' and exceeded it by {self.exceeded} test(s)' if self.exceeded else ''}")
            if self.excused_by_name:
                note += (f"; {len(self.excused_by_name)} failing test(s) excused by "
                         f"name only, the original's own failure gave no stable reading: "
                         f"{_render(self.excused_by_name)}")
            if self.doc_stand_ins:
                note += (f"; {len(self.doc_stand_ins)} doc test(s) of the "
                         f"reference pass here through their re-hosted example")
            if self.advisory_unmet:
                return (f"{note}; {len(self.advisory_unmet)} doc test(s) the "
                        f"reference passes are absent here (advisory, not gated): "
                        f"{self.render_gaps()}")
            return note
        parts = []
        if self.unmet:
            parts.append(f"{len(self.unmet)} test(s) the reference passes do not "
                         f"pass here: {_render(self.unmet)}")
        if self.unexcused_failures:
            parts.append(f"{len(self.unexcused_failures)} failing test(s) the "
                         f"reference does not excuse: {_render(self.unexcused_failures)}")
        if self.diverged:
            shown = sorted(self.diverged)[:3]
            parts.append(
                f"{len(self.diverged)} test(s) fail here, but not the way the "
                f"original fails: " + "; ".join(
                    f"{a}::{b} ({self.divergence.get((a, b), 'not read')})"
                    for a, b in shown)
                + (f"; … (+{len(self.diverged) - 3})" if len(self.diverged) > 3 else ""))
        return "; ".join(parts)


    def render_gaps(self, cap: int = 6) -> str:
        """The advisory doc tests, each with why no stand-in passed here."""
        shown = sorted(self.advisory_unmet)
        text = ", ".join(f"{a}::{b} ({self.advisory_gaps.get((a, b), 'no record')})"
                         for a, b in shown[:cap])
        return text + (f", … (+{len(shown) - cap})" if len(shown) > cap else "")


def _render(pairs: frozenset[tuple[str, str]], cap: int = 6) -> str:
    shown = sorted(f"{label}::{name}" for label, name in pairs)
    if len(shown) > cap:
        return ", ".join(shown[:cap]) + f", … (+{len(shown) - cap})"
    return ", ".join(shown)


def judge_against_reference(
    reference: ClusterReference,
    ours_passed: frozenset[tuple[str, str]],
    ours_failed: FailedReading,
) -> FloorVerdict:
    """Rule on one cluster against the reference it must meet.

    Two conditions, and the second is what keeps the generated tests required:

    1. every test the reference passes passes here (`reference.passed - ours`);
    2. every test failing here is excused by the reference — so a failing test
       the reference never had is a plain failure, exactly as it was under the
       absolute criterion.

    A failure is excused when the reference SKIPPED the test, or when the
    reference failed it the same way: its two readings agree
    (`ReferenceFailure.stable`) and this tree's reading equals them. A stable
    reference failure that this tree fails differently, or whose failure here
    was not read, is `diverged` and gates: a test the original fails cannot be
    made green, and that never made it impossible to make red in a new way
    (run `391506-3403a6a7`, 2026-10-22: `ui` was excused by name, and the same
    name covers a reconstruction that breaks another case of it). A reference
    failure with no stable reading is excused by name and reported in
    `excused_by_name`: there is no evidence to compare, and the log says so.

    Anything the reference does not have and that PASSES here is the
    reconstruction exceeding its floor; it is counted and never gated on.

    A doc test is a test under both conditions, with one advisory state: a
    doc test the reference passes that is ABSENT here — it neither passed nor
    failed, because the doc comment carrying it was not reconstructed — is
    reported and not gated (the module docstring says why), unless its
    re-hosted example stands for it here (:func:`_doc_stand_ins`). One that
    RAN here and failed is a failing test like any other.
    """
    required = reference.passed
    unmet = required - ours_passed
    failing = ours_failed.pairs
    unexcused = failing - reference.failed - reference.ignored
    excused: set[tuple[str, str]] = set(failing & reference.ignored)
    by_name: set[tuple[str, str]] = set()
    diverged: set[tuple[str, str]] = set()
    divergence: dict[tuple[str, str], str] = {}
    for pair in sorted((failing & reference.failed) - reference.ignored):
        theirs = reference.failures[pair]
        if not theirs.stable:
            excused.add(pair)
            by_name.add(pair)
            continue
        mine: FailureSignature | None = ours_failed.signatures.get(pair)
        if mine is None:
            diverged.add(pair)
            divergence[pair] = "its failure here could not be read"
        elif mine == theirs.first:
            excused.add(pair)
        else:
            assert theirs.first is not None
            diverged.add(pair)
            divergence[pair] = mine.first_difference(theirs.first)
    absent_docs = frozenset(p for p in unmet
                            if is_doc_pair(p) and p not in failing)
    stood_in, advisory, gaps = _doc_stand_ins(reference, absent_docs,
                                              ours_passed, failing)
    unmet = unmet - absent_docs
    return FloorVerdict(
        cluster=reference.cluster,
        unmet=unmet,
        unexcused_failures=unexcused,
        advisory_unmet=advisory,
        exceeded=len(ours_passed - required),
        diverged=frozenset(diverged),
        divergence=divergence,
        excused=frozenset(excused),
        excused_by_name=frozenset(by_name),
        doc_stand_ins=stood_in,
        advisory_gaps=gaps,
    )


def _doc_stand_ins(reference: ClusterReference,
                   absent: frozenset[tuple[str, str]],
                   ours_passed: frozenset[tuple[str, str]],
                   failing: frozenset[tuple[str, str]],
                   ) -> tuple[frozenset[tuple[str, str]], frozenset[tuple[str, str]],
                              dict[tuple[str, str], str]]:
    """Split the reference doc tests absent here by their stand-in.

    A stand-in that passes here meets the doc test. One that fails here is
    already a failing test this verdict gates (the reference does not have
    it), so the doc test is not counted a second time. Every other doc test
    stays advisory, with the reason: the record's, or that its stand-in did
    not run in this world."""
    stood: set[tuple[str, str]] = set()
    advisory: set[tuple[str, str]] = set()
    gaps: dict[tuple[str, str], str] = {}
    for pair in sorted(absent):
        cover = reference.doc_covers.get(pair)
        if cover is None:
            advisory.add(pair)
            gaps[pair] = (f"no origin recorded for {doc_test_file(pair[1])}"
                          if reference.doc_covers else "no doc-example origins recorded")
        elif cover.stand_in is None:
            advisory.add(pair)
            gaps[pair] = cover.gap
        elif cover.stand_in in ours_passed:
            stood.add(pair)
        elif cover.stand_in in failing:
            continue
        else:
            advisory.add(pair)
            gaps[pair] = (f"its re-hosted example {cover.stand_in[0]} did not "
                          f"run in this world")
    return frozenset(stood), frozenset(advisory), gaps


def reference_floor_close_reason(
    *,
    rc: int,
    fail_count: int,
    compile_broke: bool,
    oracle_intact: bool,
    verdict: FloorVerdict | None,
) -> str:
    """Why a FAIL sweep may close the cluster as the reference floor, or "".

    A green rc is still the primary close. This sibling is for a sweep
    whose remaining failures are all in the reference's failed-or-ignored
    set: the original crate's leftover is not a reconstruction hole. A
    red build, a short oracle, and a failing test the reference never
    had (generated behavioural tests) cannot take this path — t2a used
    to require rc==0, so a trybuild leftover the original fails on this
    rustc kept the cluster open (run 216855-03b2a21b, 2026-09-02,
    nightly at 120/123 with ui the unowned leftover).
    """
    if rc == 0 or fail_count <= 0 or compile_broke or not oracle_intact:
        return ""
    if verdict is None or not verdict.met:
        return ""
    return verdict.reason


@dataclass(frozen=True, slots=True)
class ReferenceMeasurement:
    """A whole reference run: one :class:`ClusterReference` per baked cluster,
    plus the fns the ORIGINAL leaves hollow, plus the key that decides whether
    this measurement still applies.

    `key` folds `rustc -vV` per toolchain, the env each cluster's cargo runs
    under, and a hash of the test file set. Any change re-measures — and that key is exactly
    what flips `ui`: a new nightly re-renders the diagnostics the `.stderr`
    fixtures pin, so the reference's own verdict on `ui` moves with it and the
    floor follows without anyone editing a taxonomy.
    """

    key: str
    clusters: dict[str, ClusterReference] = field(default_factory=dict)
    # (file, fn_name) the reference itself leaves `unimplemented!()`/`todo!()`.
    hollow: frozenset[tuple[str, str]] = frozenset()
    source_ref: str = ""

    @property
    def unhealthy_reason(self) -> str:
        for name in sorted(self.clusters):
            why = self.clusters[name].unhealthy_reason
            if why:
                return f"cluster '{name}': {why}"
        return "" if self.clusters else "no cluster measured"

    @property
    def usable(self) -> bool:
        return not self.unhealthy_reason

    def for_cluster(self, name: str) -> ClusterReference | None:
        return self.clusters.get(name)


def orphaned_stubs(
    hollow_here: Iterable[tuple[str, str]],
    reference_hollow: Iterable[tuple[str, str]],
) -> frozenset[tuple[str, str]]:
    """Of the fns still hollow in the reconstruction and REACHABLE under some
    baked cfg-set, the ones the reference actually implements.

    Callers must have already dropped the cfg-unreachable ones — that step is
    `cfg.unreachable_under_every_cfg_set` and it is where `anyhow`'s three
    `#[cfg(anyhow_build_probe)]` bodies leave. This step is what remains: a
    `todo!()` upstream ships and a cluster does compile, but no test exercises,
    is not a hole the reconstruction dug. Without it the gate fails a run over
    functions it reproduced exactly — two of `anyhow`'s three are byte-identical
    to upstream's own `unimplemented!()`.
    """
    return frozenset((f, n) for f, n in hollow_here) - frozenset(
        (f, n) for f, n in reference_hollow)
